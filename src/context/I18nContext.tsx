function deepMerge(base: TranslationTree, extra: TranslationTree): TranslationTree {
  const output: TranslationTree = { ...base };
  Object.entries(extra).forEach(([key, value]) => {
    const existing = output[key];
    if (existing && typeof existing === 'object' && !Array.isArray(existing) && typeof value === 'object' && !Array.isArray(value)) {
      output[key] = deepMerge(existing as TranslationTree, value as TranslationTree);
    } else {
      output[key] = value;
    }
  });
  return output;
}

